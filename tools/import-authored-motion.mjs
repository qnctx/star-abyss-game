// Reproducible, offline GLB -> C-suit animation retarget. No runtime asset fetch.
import fs from 'node:fs';
import crypto from 'node:crypto';
import * as THREE from 'three';
import {HUMANOID_RIG} from '../playable/src/humanoid-rig.mjs';
const filename='playable/assets/animations/UAL1_Standard.glb', bytes=fs.readFileSync(filename);
const jsonLength=bytes.readUInt32LE(12), data=JSON.parse(bytes.subarray(20,20+jsonLength).toString());
const binary=bytes.subarray(28+jsonLength);
function accessor(index){
  const a=data.accessors[index],v=data.bufferViews[a.bufferView];
  if(a.componentType!==5126||a.sparse)throw new Error('Expected dense float animation accessor');
  const size={SCALAR:1,VEC3:3,VEC4:4}[a.type],out=[];
  for(let i=0;i<a.count;i++)for(let c=0;c<size;c++)out.push(binary.readFloatLE((v.byteOffset||0)+(a.byteOffset||0)+i*(v.byteStride||size*4)+c*4));
  return out;
}
const source=data.nodes.map(n=>{const o=new THREE.Object3D();o.name=n.name;o.position.fromArray(n.translation||[0,0,0]);o.quaternion.fromArray(n.rotation||[0,0,0,1]);return o;});
data.nodes.forEach((n,i)=>n.children?.forEach(c=>source[i].add(source[c])));
const scene=new THREE.Group();data.nodes.forEach((_,i)=>{if(!source[i].parent)scene.add(source[i]);});scene.updateMatrixWorld(true);
const sourceByName=Object.fromEntries(source.map(o=>[o.name,o]));
const conversion=new THREE.Quaternion().setFromAxisAngle(new THREE.Vector3(0,1,0),Math.PI);
const corrections=HUMANOID_RIG.map(([name,,,src])=>{
  const world=conversion.clone().multiply(sourceByName[src].getWorldQuaternion(new THREE.Quaternion()));
  // Source is a T pose; the C garment was built with arms down. Retarget through
  // an explicit matching T pose, not a rest-delta that folds arms into the body.
  const target=new THREE.Quaternion();
  if(/shoulder|elbow|wrist/.test(name))target.setFromAxisAngle(new THREE.Vector3(0,0,1),name.endsWith('L')?-Math.PI/2:Math.PI/2);
  return world.invert().multiply(target);
});
const pelvisRest=sourceByName.pelvis.getWorldPosition(new THREE.Vector3());
const names={idle:'Idle_Loop',walk:'Walk_Loop',jog:'Jog_Fwd_Loop',sprint:'Sprint_Loop',flight:'Jump_Loop',seated:'Driving_Loop',crouchIdle:'Crouch_Idle_Loop',crouchWalk:'Crouch_Fwd_Loop'};
const round=v=>+v.toFixed(6), clips={};
for(const [key,name]of Object.entries(names)){
  const animation=data.animations.find(a=>a.name===name);if(!animation)throw new Error('Missing '+name);
  const channels=animation.channels.map(c=>{const sampler=animation.samplers[c.sampler];if(sampler.interpolation&&sampler.interpolation!=='LINEAR')throw new Error('Unsupported interpolation');return{node:source[c.target.node],path:c.target.path,times:accessor(sampler.input),values:accessor(sampler.output)};});
  const duration=Math.max(...channels.map(c=>c.times.at(-1))), count=Math.round(duration*60), frames=[];
  for(let f=0;f<=count;f++){
    const t=f/count*duration;
    for(const c of channels){
      if(c.path==='scale')continue;
      let i=0;while(i<c.times.length-2&&c.times[i+1]<t)i++;
      const b=Math.min(i+1,c.times.length-1),alpha=THREE.MathUtils.clamp((t-c.times[i])/Math.max(1e-8,c.times[b]-c.times[i]),0,1);
      if(c.path==='rotation')c.node.quaternion.fromArray(c.values,i*4).slerp(new THREE.Quaternion().fromArray(c.values,b*4),alpha);
      else c.node.position.fromArray(c.values,i*3).lerp(new THREE.Vector3().fromArray(c.values,b*3),alpha);
    }
    scene.updateMatrixWorld(true);
    const world=HUMANOID_RIG.map(([, , ,src],i)=>conversion.clone().multiply(sourceByName[src].getWorldQuaternion(new THREE.Quaternion())).multiply(corrections[i]).normalize());
    const q=world.flatMap((w,i)=>{const p=HUMANOID_RIG[i][1];return(p<0?w:world[p].clone().invert().multiply(w)).normalize().toArray();});
    const delta=sourceByName.pelvis.getWorldPosition(new THREE.Vector3()).sub(pelvisRest).applyQuaternion(conversion).multiplyScalar(1.06);
    frames.push([delta.x,delta.y,delta.z,...q].map(round));
  }
  clips[key]={source:name,duration,frames};
}
const output={source:'Quaternius UAL1 Standard / CC0',sha256:crypto.createHash('sha256').update(bytes).digest('hex'),bones:HUMANOID_RIG.length,clips};
fs.writeFileSync('playable/src/authored-motion-data.mjs','// Generated by tools/import-authored-motion.mjs. CC0; see assets/animations/CREDITS.md.\nexport default '+JSON.stringify(output)+';\n');
console.log(JSON.stringify(Object.fromEntries(Object.entries(clips).map(([key,c])=>[key,{source:c.source,duration:c.duration,frames:c.frames.length}]))));
