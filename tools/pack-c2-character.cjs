const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const bytes=fs.readFileSync(path.join(root,'playable/assets/characters/c2-explorer.glb'));
const hash=crypto.createHash('sha256').update(bytes).digest('hex');
fs.writeFileSync(path.join(root,'playable/assets/characters/c2-explorer-data.mjs'),`// Generated by tools/pack-c2-character.cjs from c2-explorer.glb.\nexport const sha256='${hash}';\nexport default '${bytes.toString('base64')}';\n`);
console.log(JSON.stringify({bytes:bytes.length,sha256:hash}));
