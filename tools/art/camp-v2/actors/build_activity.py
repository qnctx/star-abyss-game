def clamp(v,a=0,b=1):return max(a,min(b,v))
def angles(p):
    p%=1
    if p<.5:z=STRIDE*.25-STRIDE*p;lift=0
    else:
        q=(p-.5)*2;z=-STRIDE*.25+STRIDE*.5*(q*q*(3-2*q));lift=.035*math.sin(math.pi*q)**2
    a=H*.23;b=H*.21;dy=a+b-DROP-lift;d=math.hypot(dy,z)
    knee=math.pi-math.acos(clamp((a*a+b*b-d*d)/(2*a*b),-1,1))
    thigh=math.atan2(-z,dy)-math.acos(clamp((a*a+d*d-b*b)/(2*a*d),-1,1))
    return [thigh,knee,-thigh-knee]
