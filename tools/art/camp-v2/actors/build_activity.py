def weights(x,h):
    if h<.51:
        r=clamp((x/H+.055)/.11);leg=clamp((.51-h)/.12);u=6;l=7;t=clamp((.32-h)/.10)
        if h<.15:u=7;l=8;t=clamp((.15-h)/.07)
        e=[(0,1-leg),(u,leg*(1-r)*(1-t)),(l,leg*(1-r)*t),(u+3,leg*r*(1-t)),(l+3,leg*r*t)]
        e=sorted([v for v in e if v[1]>0],key=lambda v:-v[1])[:4];s=sum(v[1] for v in e)
        return [(i,w/s) for i,w in e]
    j=0;t=0
    if h>.84:j=3;t=clamp((h-.84)/.05)
    elif abs(x)>H*.19 and .40<h<.82:j=4 if x<0 else 5;t=clamp((abs(x)/H-.16)/.08)
    elif h>.55:j=1;t=clamp((h-.55)/.13)
    return [(0,1-t),(j,t)]
